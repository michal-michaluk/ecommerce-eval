#!/usr/bin/env python3
"""Acceptance checks for the rendered deliverables — the artifact, not the markdown source.

A document can be correct in source and wrong on the page: a title page that swallowed the
table of contents, a footer that vanishes after page 3, a chapter that fell out of the
composition, provenance or diagram syntax that reached the reader. This script renders
nothing; it reads ``docs/_build/*.pdf`` and ``*.html`` and asserts on them.

Every document is declared under ``documents`` in ``docs/scripts/config.json``:

    {"slug": "system-documentation", "title": "…", "max_pages": 60,
     "required": ["Appendix A", "GAP-1"], "forbidden": ["Controller", "findById"]}

``required`` are the strings a reader must find; ``forbidden`` are the strings that may exist
in source but must never reach the page — identifier names, method names, class names.
``max_pages`` bounds the length, so a document that swallows every payload stops being
shipped before it stops being read. A zero or an empty list skips that check.

Always asserted, for every document: page 1 carries the title and no table of contents, the
table of contents starts on page 2, every page after page 1 carries a ``<n> / <total>``
footer, and no provenance or diagram syntax appears anywhere in the PDF or the HTML.

Prerequisites: ``pdftotext`` and ``pdfinfo`` (poppler). Reads only; exits 1 on any failure.
"""

from __future__ import annotations

import argparse
import html as html_module
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config  # noqa: E402

BUILD = config.DOCS / "_build"

LEAKS = ("evidence:", "generated by docs", "flowchart", "sequenceDiagram", "C4Context")

failures: list[str] = []


def check(condition: bool, message: str) -> None:
    print(("PASS " if condition else "FAIL ") + message)
    if not condition:
        failures.append(message)


def sh(*args: str) -> str:
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"{args[0]} failed: {result.stderr.strip()[:400]}")
    return result.stdout


def pages(path: Path) -> list[str]:
    total = int(re.search(r"Pages:\s+(\d+)", sh("pdfinfo", str(path))).group(1))
    return [
        sh("pdftotext", "-layout", "-f", str(number), "-l", str(number), str(path), "-")
        for number in range(1, total + 1)
    ]


def text_of(path: Path) -> str:
    return sh("pdftotext", str(path), "-")


def html_text(path: Path) -> str:
    return re.sub(r"<[^>]+>", " ", html_module.unescape(path.read_text(encoding="utf-8")))


def audit(document: dict) -> None:
    slug = document["slug"]
    pdf = BUILD / f"{slug}.pdf"
    page = BUILD / f"{slug}.html"
    if not pdf.is_file():
        check(False, f"{slug}: {pdf.name} exists — run quarto render first")
        return

    rendered = pages(pdf)
    flat, total = text_of(pdf), len(rendered)
    plain_html = html_text(page) if page.is_file() else ""

    title = document.get("title", "")
    if title:
        check(title in rendered[0], f"{slug}: page 1 carries {title!r}")
    check("Table of Contents" not in rendered[0], f"{slug}: page 1 has no table of contents")
    toc = [number for number, body in enumerate(rendered, start=1) if "Table of Contents" in body]
    check(toc == [2], f"{slug}: table of contents starts on its own page (pages {toc})")

    missing_footer = [
        number for number, body in enumerate(rendered[1:], start=2)
        if not (match := re.compile(r"(\d+)\s*/\s*%d" % total).search(body))
        or int(match.group(1)) != number
    ]
    check(not missing_footer, f"{slug}: footer '<page> / {total}' on every page after page 1 "
                              f"(bad: {missing_footer[:5]})")

    for needle in document.get("required", []):
        check(needle in flat, f"{slug}: pdf contains {needle!r}")
    for needle in document.get("forbidden", []):
        check(needle not in flat, f"{slug}: pdf does not contain {needle!r}")

    for needle in LEAKS:
        check(needle not in flat, f"{slug}: pdf does not contain {needle!r}")
        if plain_html:
            check(needle not in plain_html, f"{slug}: html does not contain {needle!r}")

    cap = document.get("max_pages") or 0
    if cap:
        check(total <= cap, f"{slug}: stays within {cap} pages ({total})")
    print(f"     {slug}: {total} pages")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="check-rendered.py",
        description="Assert on the rendered PDF and HTML deliverables. Reads only.",
    )
    parser.add_argument("--slug", help="check one document instead of every configured one")
    args = parser.parse_args(argv)

    documents = config.DATA["documents"]
    if args.slug:
        documents = [document for document in documents if document["slug"] == args.slug]
        if not documents:
            raise SystemExit(f"no document {args.slug!r} in docs/scripts/config.json")
    for document in documents:
        audit(document)

    print()
    print(f"FAILURES: {len(failures)}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
